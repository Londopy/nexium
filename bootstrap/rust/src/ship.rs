pub fn platform_tag(target: &str) -> String {
    let t = target.to_ascii_lowercase();
    if t.contains("windows") {
        if t.contains("aarch64") {
            "win_arm64".into()
        } else {
            "win_amd64".into()
        }
    } else if t.contains("macos") || t.contains("darwin") {
        if t.contains("aarch64") {
            "macosx_11_0_arm64".into()
        } else {
            "macosx_10_13_x86_64".into()
        }
    } else if t.contains("linux") {
        if t.contains("aarch64") {
            "manylinux_2_17_aarch64".into()
        } else {
            "manylinux_2_17_x86_64".into()
        }
    } else {
        "any".into()
    }
}

fn crc32(data: &[u8]) -> u32 {
    let mut table = [0u32; 256];
    for i in 0..256u32 {
        let mut c = i;
        for _ in 0..8 {
            c = if c & 1 != 0 { 0xEDB88320 ^ (c >> 1) } else { c >> 1 };
        }
        table[i as usize] = c;
    }
    let mut crc = 0xFFFFFFFFu32;
    for &b in data {
        crc = table[((crc ^ b as u32) & 0xff) as usize] ^ (crc >> 8);
    }
    crc ^ 0xFFFFFFFF
}

/// Write a stored (uncompressed) zip archive.
pub fn write_zip(path: &Path, files: &[(String, Vec<u8>)]) -> std::io::Result<()> {
    let mut out: Vec<u8> = Vec::new();
    let mut central: Vec<u8> = Vec::new();
    for (name, data) in files {
        let offset = out.len() as u32;
        let crc = crc32(data);
        let nb = name.as_bytes();
        // local header
        out.extend_from_slice(&[0x50, 0x4b, 0x03, 0x04, 20, 0, 0, 0, 0, 0, 0, 0, 0, 0]);
        out.extend_from_slice(&crc.to_le_bytes());
        out.extend_from_slice(&(data.len() as u32).to_le_bytes());
        out.extend_from_slice(&(data.len() as u32).to_le_bytes());
        out.extend_from_slice(&(nb.len() as u16).to_le_bytes());
        out.extend_from_slice(&0u16.to_le_bytes());
        out.extend_from_slice(nb);
        out.extend_from_slice(data);
        // central directory
        central.extend_from_slice(&[0x50, 0x4b, 0x01, 0x02, 20, 3, 20, 0, 0, 0, 0, 0, 0, 0, 0, 0]);
        central.extend_from_slice(&crc.to_le_bytes());
        central.extend_from_slice(&(data.len() as u32).to_le_bytes());
        central.extend_from_slice(&(data.len() as u32).to_le_bytes());
        central.extend_from_slice(&(nb.len() as u16).to_le_bytes());
        central.extend_from_slice(&0u16.to_le_bytes());
        central.extend_from_slice(&0u16.to_le_bytes());
        central.extend_from_slice(&0u16.to_le_bytes());
        central.extend_from_slice(&0u16.to_le_bytes());
        central.extend_from_slice(&(0o100644u32 << 16).to_le_bytes());
        central.extend_from_slice(&offset.to_le_bytes());
        central.extend_from_slice(nb);
    }
    let cd_offset = out.len() as u32;
    let cd_size = central.len() as u32;
    out.extend_from_slice(&central);
    out.extend_from_slice(&[0x50, 0x4b, 0x05, 0x06, 0, 0, 0, 0]);
    out.extend_from_slice(&(files.len() as u16).to_le_bytes());
    out.extend_from_slice(&(files.len() as u16).to_le_bytes());
    out.extend_from_slice(&cd_size.to_le_bytes());
    out.extend_from_slice(&cd_offset.to_le_bytes());
    out.extend_from_slice(&0u16.to_le_bytes());
    std::fs::write(path, out)
}

pub fn build_wheel(out_dir: &Path, name: &str, version: &str, tag: &str, package_files: &[(String, Vec<u8>)], summary: &str) -> std::io::Result<std::path::PathBuf> {
    let dist = format!("{}-{}.dist-info", name, version);
    let mut files: Vec<(String, Vec<u8>)> = package_files.to_vec();
    let metadata = format!("Metadata-Version: 2.1\nName: {}\nVersion: {}\nSummary: {}\nRequires-Python: >=3.8\n", name, version, summary);
    let wheel = format!("Wheel-Version: 1.0\nGenerator: nx\nRoot-Is-Purelib: false\nTag: py3-none-{}\n", tag);
    files.push((format!("{}/METADATA", dist), metadata.into_bytes()));
    files.push((format!("{}/WHEEL", dist), wheel.into_bytes()));
    files.push((format!("{}/top_level.txt", dist), format!("{}\n", name).into_bytes()));
    let mut record = String::new();
    for (n, d) in &files {
        let _ = writeln!(record, "{},sha256=,{}", n, d.len());
    }
    let _ = writeln!(record, "{}/RECORD,,", dist);
    files.push((format!("{}/RECORD", dist), record.into_bytes()));
    let path = out_dir.join(format!("{}-{}-py3-none-{}.whl", name, version, tag));
    write_zip(&path, &files)?;
    Ok(path)
}
